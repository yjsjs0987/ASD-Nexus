export function resolveLocale(systemLocale?: string): Locale {
  if (!systemLocale) return "ko";
  return systemLocale.toLowerCase().startsWith("en") ? "en" : "ko";
}

export function t(locale: Locale, key: string): string {
  return STRINGS[locale]?.[key] ?? STRINGS.ko[key] ?? key;
}
